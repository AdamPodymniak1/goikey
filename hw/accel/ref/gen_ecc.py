#!/usr/bin/env python3
"""Generate rtl/ecc_ucode.vh + rtl/ecc_const.vh + ref/ecc_map.py from the microprograms."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
import ecc_asm as E
OUT = os.environ.get('GEN_OUT') or os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'rtl')
if os.environ.get('TRO_MASTER_HEX'): E.set_master(bytes.fromhex(os.environ['TRO_MASTER_HEX']))
A = E.build(); code = A.link()
assert len(code) <= 1536
with open(os.path.join(OUT, "ecc_ucode.vh"), "w") as f:
    f.write("// generated by ref/gen_ecc.py: microcode ROM image\n")
    for i, w in enumerate(code): f.write(f"uc[{i}] = 32'h{w:08x};\n")
with open(os.path.join(OUT, "ecc_const.vh"), "w") as f:
    f.write("// generated by ref/gen_ecc.py: constant ROM image (16-bit words, little endian)\n")
    for i, n in enumerate(E.CNAMES):
        v = E.CONSTS[n]
        for w in range(16): f.write(f"km[{i*16+w}] = 16'h{(v >> (16*w)) & 0xffff:04x};\n")
with open(os.path.join(os.path.dirname(__file__), "ecc_map.py"), "w") as f:
    f.write("# generated: register map and entry points\nREGS = %r\nENTRIES = %r\n" % (A.regs, A.entries))
print(len(code), "instructions,", len(E.CNAMES), "constants; entries:", A.entries)
with open(os.path.join(OUT, "ecc_cmdtab.vh"), "w") as f:
    f.write("// generated by ref/gen_ecc.py: command byte -> microprogram entry pc  ({valid, pc[10:0]})\n")
    f.write("function [11:0] cmd_entry(input [7:0] c);\n  case (c)\n")
    for c, n in E.CMD_TABLE.items(): f.write(f"    8'h{c:02x}: cmd_entry = {{1'b1, 11'd{A.entries[n]}}};\n")
    f.write("    default: cmd_entry = 12'd0;\n  endcase\nendfunction\n")
with open(os.path.join(os.path.dirname(__file__), "ecc_map.py"), "w") as f:
    f.write("# generated: register map and entry points\nREGS = %r\nENTRIES = %r\n" % (A.regs, A.entries))
