#!/usr/bin/env python3
"""Generate rtl/aes_sbox_tower.vh: ONE AES S-box for both directions, computed in the tower field GF(((2^2)^2)^2).

    forward  S(x)    = A * inv(x) + 0x63
    inverse  S^-1(y) = inv(A^-1 * (y + 0x63))

inv() is done in the tower field (an isomorphic image of GF(2^8)), so only the linear input / output maps depend on
the direction: in = dec ? T*A^-1*(y + 63) : T*x,  out = dec ? T^-1*r : A*T^-1*r + 63. The GF(16) inverse is a
4-input table (one LUT4 per output bit). Verified exhaustively against the FIPS-197 tables (self-check below and
tb/tb_sbox_tower.v)."""
import os

def gmul(a, b, poly=0x11B):                       # GF(2^8), AES polynomial
    r = 0
    while b:
        if b & 1: r ^= a
        a <<= 1
        if a & 0x100: a ^= poly
        b >>= 1
    return r

def ginv(a):
    return 0 if a == 0 else next(b for b in range(1, 256) if gmul(a, b) == 1)

SBOX = []
for x in range(256):
    v = ginv(x); s = 0x63
    for i in range(8):
        bit = ((v >> i) ^ (v >> ((i + 4) % 8)) ^ (v >> ((i + 5) % 8)) ^ (v >> ((i + 6) % 8)) ^ (v >> ((i + 7) % 8))) & 1
        s ^= bit << i
    SBOX.append(s)
ISBOX = [SBOX.index(y) for y in range(256)]

# ---- tower field arithmetic: GF(4) = GF(2)[w]/(w^2+w+1); GF(16) = GF(4)[y]/(y^2+y+PHI); GF(256) = GF(16)[z]/(z^2+z+LAM)
def m4(a, b):
    a1, a0, b1, b0 = a >> 1, a & 1, b >> 1, b & 1
    hi = (a1 & b1) ^ (a1 & b0) ^ (a0 & b1); lo = (a1 & b1) ^ (a0 & b0)
    return (hi << 1) | lo
PHI = 2                                            # w: y^2+y+w is irreducible over GF(4)
def m16(a, b):
    ah, al, bh, bl = a >> 2, a & 3, b >> 2, b & 3
    hh = m4(ah, bh)
    return ((hh ^ m4(ah, bl) ^ m4(al, bh)) << 2) | (m4(hh, PHI) ^ m4(al, bl))
def inv16(a): return 0 if a == 0 else next(b for b in range(1, 16) if m16(a, b) == 1)
def irreducible16(lam): return all(m16(t, t) ^ t ^ lam for t in range(16))
LAM = next(l for l in range(1, 16) if irreducible16(l))
def m256(a, b):
    ah, al, bh, bl = a >> 4, a & 15, b >> 4, b & 15
    hh = m16(ah, bh)
    return ((hh ^ m16(ah, bl) ^ m16(al, bh)) << 4) | (m16(hh, LAM) ^ m16(al, bl))
def tinv(a):
    ah, al = a >> 4, a & 15
    d = m16(m16(ah, ah), LAM) ^ m16(ah, al) ^ m16(al, al)
    di = inv16(d)
    return (m16(ah, di) << 4) | m16(ah ^ al, di)

# ---- isomorphism: AES element sum a_i x^i -> sum a_i beta^i, beta a root of x^8+x^4+x^3+x+1 in the tower field
def tpow(b, n):
    r = 1
    for _ in range(n): r = m256(r, b)
    return r
def is_root(b): return tpow(b, 8) ^ tpow(b, 4) ^ tpow(b, 3) ^ b ^ 1 == 0
BETA = next(b for b in range(2, 256) if is_root(b))
COLS = [tpow(BETA, i) for i in range(8)]          # T: column i = image of x^i
def apply(cols, v):
    r = 0
    for i in range(8):
        if (v >> i) & 1: r ^= cols[i]
    return r
def mat_inv(cols):
    return [next(v for v in range(256) if apply(cols, v) == 1 << i) for i in range(8)]
T, TI = COLS, mat_inv(COLS)
A = [apply([0] * 0 + [0x1F, 0x3E, 0x7C, 0xF8, 0xF1, 0xE3, 0xC7, 0x8F], 1 << i) for i in range(8)]   # affine matrix (columns)
AI = mat_inv(A)
def compose(f, g): return [apply(f, apply(g, 1 << i)) for i in range(8)]  # f o g
F_IN, F_OUT = T, compose(A, TI)
I_IN, I_OUT = compose(T, AI), TI
I_IN_C = apply(I_IN, 0x63)                         # T*A^-1*(y+63) = T*A^-1*y + T*A^-1*63

for x in range(256):                               # self-check of the whole construction
    assert apply(F_OUT, tinv(apply(F_IN, x))) ^ 0x63 == SBOX[x]
    assert apply(I_OUT, tinv(apply(I_IN, x) ^ I_IN_C)) == ISBOX[x]

def rows(cols):                                    # output bit j = XOR of input bits i with cols[i] bit j
    return [[i for i in range(8) if (cols[i] >> j) & 1] for j in range(8)]
def xor_terms(v, idx): return " ^ ".join(f"{v}[{i}]" for i in idx) if idx else "1'b0"

def m4v(a, b): return f"sbt_m4({a}, {b})"
o = ["// generated by ref/gen_sbox_tower.py: shared forward / inverse AES S-box in GF(((2^2)^2)^2)",
     "function [1:0] sbt_m4(input [1:0] a, input [1:0] b);",
     "    sbt_m4 = {(a[1] & b[1]) ^ (a[1] & b[0]) ^ (a[0] & b[1]), (a[1] & b[1]) ^ (a[0] & b[0])};",
     "endfunction",
     "function [3:0] sbt_m16(input [3:0] a, input [3:0] b);",
     "    reg [1:0] hh;",
     "    begin",
     "        hh = sbt_m4(a[3:2], b[3:2]);",
     f"        sbt_m16 = {{hh ^ sbt_m4(a[3:2], b[1:0]) ^ sbt_m4(a[1:0], b[3:2]), sbt_m4(hh, 2'd{PHI}) ^ sbt_m4(a[1:0], b[1:0])}};",
     "    end",
     "endfunction",
     "function [3:0] sbt_inv16(input [3:0] a);",
     "    case (a)"]
for a in range(16): o.append(f"    4'd{a}: sbt_inv16 = 4'd{inv16(a)};")
o += ["    default: sbt_inv16 = 4'd0;", "    endcase", "endfunction",
      "function [7:0] aes_sbox_fi(input [7:0] x, input inv);   // inv=0: S(x), inv=1: S^-1(x)",
      "    reg [7:0] tf, ti, t, r, of, oi; reg [3:0] d, di;",
      "    begin"]
for j, idx in enumerate(rows(F_IN)): o.append(f"        tf[{j}] = {xor_terms('x', idx)};")
for j, idx in enumerate(rows(I_IN)): o.append(f"        ti[{j}] = {xor_terms('x', idx)}{' ^ 1' if (I_IN_C >> j) & 1 else ''};")
o += ["        t  = inv ? ti : tf;",
      f"        d  = sbt_m16(sbt_m16(t[7:4], t[7:4]), 4'd{LAM}) ^ sbt_m16(t[7:4], t[3:0]) ^ sbt_m16(t[3:0], t[3:0]);",
      "        di = sbt_inv16(d);",
      "        r  = {sbt_m16(t[7:4], di), sbt_m16(t[7:4] ^ t[3:0], di)};"]
for j, idx in enumerate(rows(F_OUT)): o.append(f"        of[{j}] = {xor_terms('r', idx)}{' ^ 1' if (0x63 >> j) & 1 else ''};")
for j, idx in enumerate(rows(I_OUT)): o.append(f"        oi[{j}] = {xor_terms('r', idx)};")
o += ["        aes_sbox_fi = inv ? oi : of;", "    end", "endfunction", ""]

here = os.path.dirname(os.path.abspath(__file__))
out = os.environ.get("GEN_OUT") or os.path.join(here, "..", "rtl")
with open(os.path.join(out, "aes_sbox_tower.vh"), "w") as f: f.write("\n".join(o))
# exhaustive simulation test bench
tb = ["`timescale 1ns/1ps", "module tb_sbox_tower;", "`include \"aes_sbox_tower.vh\"", "integer x, fails = 0;",
      "reg [7:0] sf [0:255]; reg [7:0] si [0:255];", "initial begin"]
for x in range(256): tb.append(f"    sf[{x}] = 8'h{SBOX[x]:02x}; si[{x}] = 8'h{ISBOX[x]:02x};")
tb += ["    for (x = 0; x < 256; x = x + 1) begin",
       "        if (aes_sbox_fi(x[7:0], 1'b0) !== sf[x]) begin fails = fails + 1; $display(\"FAIL S(%02x)\", x); end",
       "        if (aes_sbox_fi(x[7:0], 1'b1) !== si[x]) begin fails = fails + 1; $display(\"FAIL Si(%02x)\", x); end",
       "    end",
       "    if (fails == 0) $display(\"ALL PASS (512 S-box values)\"); else $display(\"%0d FAILURES\", fails);",
       "    $finish;", "end", "endmodule", ""]
with open(os.path.join(here, "..", "tb", "tb_sbox_tower.v"), "w") as f: f.write("\n".join(tb))
print(f"PHI={PHI} LAM={LAM} BETA=0x{BETA:02x}: model self-check OK")
