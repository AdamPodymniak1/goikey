#!/usr/bin/env python3
"""Generate rtl/sha2_rom.vh: initial contents of the sha2_unit RAM (64-bit words) - SHA-256 / SHA-512 round constants
and initial hash values, computed from the primes (FIPS 180-4) with exact integer roots."""
import os

def primes(n):
    p, c = [], 2
    while len(p) < n:
        if all(c % q for q in p): p.append(c)
        c += 1
    return p

def iroot(x, k):                                   # floor(x ** (1/k)) for big integers
    r = 1 << ((x.bit_length() + k - 1) // k)
    while True:
        s = ((k - 1) * r + x // r ** (k - 1)) // k
        if s >= r: break
        r = s
    while r ** k > x: r -= 1
    while (r + 1) ** k <= x: r += 1
    return r

def frac_bits(p, k, bits):                         # first `bits` fractional bits of p^(1/k)
    return iroot(p << (k * bits), k) & ((1 << bits) - 1)

K256 = [frac_bits(p, 3, 32) for p in primes(64)]
K512 = [frac_bits(p, 3, 64) for p in primes(80)]
IV256 = [frac_bits(p, 2, 32) for p in primes(8)]
IV512 = [frac_bits(p, 2, 64) for p in primes(8)]
assert K256[0] == 0x428a2f98 and K512[79] == 0x6c44198c4a475817 and IV256[0] == 0x6a09e667 and IV512[7] == 0x5be0cd19137e2179

# word addresses - keep in sync with rtl/sha2_unit.v
A_K256, A_K512, A_IV256, A_IV512 = 128, 192, 272, 280
o = ["// generated by ref/gen_sha2_rom.py: sha2_unit RAM initial contents (K256 @128, K512 @192, IV256 @272, IV512 @280)"]
for base, vals in ((A_K256, K256), (A_K512, K512), (A_IV256, IV256), (A_IV512, IV512)):
    for i, v in enumerate(vals): o.append(f"hm[{base + i}] = 64'h{v:016x};")
out = os.environ.get("GEN_OUT") or os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "rtl")
with open(os.path.join(out, "sha2_rom.vh"), "w") as f: f.write("\n".join(o) + "\n")
print("sha2_rom.vh:", len(o) - 1, "words")
